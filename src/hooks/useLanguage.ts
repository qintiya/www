export function useLanguage() {
  const [lang, setLang] = useState<Lang>("id");
  const t = useCallback((key: string) => dict[lang][key] ?? key, [lang]);
  const dir = lang === "ar" ? "rtl" : "ltr";
  return { lang, setLang, t, dir };
}